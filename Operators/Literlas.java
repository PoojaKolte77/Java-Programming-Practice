public class Literlas {
    
    public static void main(String[] args) {
        // Integer literal
        int num = 100;

        // Floating-point literal
        double pi = 3.14;

        // Character literal
        char letter = 'A';

        // String literal
        String greeting = "Hello, World!";

        // Boolean literal
        boolean isJavaFun = true;

        System.out.println("Integer Literal: " + num);
        System.out.println("Floating-point Literal: " + pi);
        System.out.println("Character Literal: " + letter);
        System.out.println("String Literal: " + greeting);
        System.out.println("Boolean Literal: " + isJavaFun);
    }
}
